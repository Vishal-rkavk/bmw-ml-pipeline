"""Step 5: generate text for BMW-related prompts — fine-tuned vs base.

Prompts are press-release openings, the pattern the model was trained
on. Each prompt is generated by both models with the same per-prompt
seed, so the effect of adaptation is visible side by side and the
outputs are reproducible.
"""

import sys
import time
from datetime import datetime, timezone

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

from pipeline import config, metrics

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

PROMPTS = [
    "The new BMW",
    "Munich.",
    "The BMW Group delivered",
    "The BMW iX4 is",
    "BMW Motorrad presents",
    "The BMW M3",
    "Sustainability at the BMW Group means",
    "The Neue Klasse platform",
]


def generate(model, tokenizer, prompt: str, seed: int) -> str:
    """Sample one continuation for a prompt (deterministic per seed)."""
    torch.manual_seed(seed)
    inputs = tokenizer(prompt, return_tensors="pt").to(DEVICE)
    output = model.generate(
        **inputs,
        max_new_tokens=config.GEN_MAX_NEW_TOKENS,
        do_sample=True,
        temperature=config.GEN_TEMPERATURE,
        top_p=config.GEN_TOP_P,
        pad_token_id=tokenizer.eos_token_id,
    )
    return tokenizer.decode(output[0], skip_special_tokens=True)


def main() -> int:
    config.ensure_dirs()
    started = time.time()

    tokenizer = AutoTokenizer.from_pretrained(config.MODEL_DIR)
    models = {
        "base": AutoModelForCausalLM.from_pretrained(
            config.MODEL_ID, revision=config.MODEL_REVISION).to(DEVICE),
        "fine-tuned": AutoModelForCausalLM.from_pretrained(
            config.MODEL_DIR).to(DEVICE),
    }

    sections = []
    for i, prompt in enumerate(PROMPTS):
        sections.append(f'## Prompt: "{prompt}"\n')
        for name, model in models.items():
            text = generate(model, tokenizer, prompt, config.SEED + i)
            sections.append(f"### {name}\n\n{text}\n")
        sections.append("---\n")
        print(f"[generate] {i + 1}/{len(PROMPTS)} prompts done")

    header = (
        f"# BMW prompt generations\n\n"
        f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n\n"
        f"- fine-tuned: `artifacts/model` (trained on BMW press releases)\n"
        f"- base: `{config.MODEL_ID}` @ `{config.MODEL_REVISION[:8]}`\n"
        f"- settings: temperature {config.GEN_TEMPERATURE}, "
        f"top_p {config.GEN_TOP_P}, max_new_tokens {config.GEN_MAX_NEW_TOKENS}, "
        f"seed {config.SEED}+i per prompt\n\n---\n\n"
    )
    out = config.GENERATIONS_DIR / "generations.md"
    out.write_text(header + "\n".join(sections), encoding="utf-8")

    duration = time.time() - started
    print(f"[generate] {len(PROMPTS)} prompts x {len(models)} models "
          f"in {duration:.0f}s -> {out}")

    metrics.push("bmw-generate", values={
        "bmw_generation_prompts": len(PROMPTS),
        "bmw_generation_duration_seconds": round(duration, 1)})
    return 0


if __name__ == "__main__":
    sys.exit(main())
